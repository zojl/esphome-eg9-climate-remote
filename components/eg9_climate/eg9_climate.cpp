EG9Climate::EG9Climate() : climate::Climate() {
  this->mode = climate::CLIMATE_MODE_OFF;
  this->target_temperature = 24;
  this->fan_mode = climate::CLIMATE_FAN_AUTO;
  this->swing_mode = climate::CLIMATE_SWING_OFF;
}

void EG9VaneSelect::control(const std::string &value) {
  this->publish_state(value);
  if (this->parent_ != nullptr) {
    this->parent_->set_vane_position(value);
  }
}

void EG9Climate::setup() {
  if (!this->has_vane_select_) {
    this->set_supported_custom_presets({
        "Auto",
        "Top",
        "Medium-Top",
        "Medium",
        "Medium-Bottom",
        "Bottom",
    });
    if (!this->has_custom_preset()) {
      this->set_custom_preset_("Auto");
    }
  }
}

climate::ClimateTraits EG9Climate::traits() {
  auto traits = climate::ClimateTraits();
  
  traits.set_supported_modes({
      climate::CLIMATE_MODE_OFF,
      climate::CLIMATE_MODE_COOL,
      climate::CLIMATE_MODE_HEAT,
  });
  traits.set_supported_fan_modes({
      climate::CLIMATE_FAN_AUTO,
      climate::CLIMATE_FAN_LOW,
      climate::CLIMATE_FAN_MEDIUM,
      climate::CLIMATE_FAN_HIGH,
      climate::CLIMATE_FAN_QUIET,
  });
  traits.set_supported_swing_modes({
      climate::CLIMATE_SWING_OFF,
      climate::CLIMATE_SWING_VERTICAL,
  });
  traits.set_visual_min_temperature(16);
  traits.set_visual_max_temperature(31);
  traits.set_visual_temperature_step(1.0f);
  return traits;
}

void EG9Climate::set_vane_position(const std::string &position) {
  if (position == "Top") {
    this->current_swing_code_ = SWING_CODE_TOP;
  } else if (position == "Medium-Top") {
    this->current_swing_code_ = SWING_CODE_MEDIUM_TOP;
  } else if (position == "Medium") {
    this->current_swing_code_ = SWING_CODE_MEDIUM;
  } else if (position == "Medium-Bottom") {
    this->current_swing_code_ = SWING_CODE_MEDIUM_BOTTOM;
  } else if (position == "Bottom") {
    this->current_swing_code_ = SWING_CODE_BOTTOM;
  } else {
    this->current_swing_code_ = SWING_CODE_AUTO;
  }
  // Setting a fixed vane position stops continuous vertical swing
  this->swing_mode = climate::CLIMATE_SWING_OFF;
  if (!this->has_vane_select_) {
    this->set_custom_preset_(position.c_str());
  }
  this->transmit_state();
  this->publish_state();
}

void EG9Climate::control(const climate::ClimateCall &call) {
  if (call.get_mode().has_value())
    this->mode = *call.get_mode();
  if (call.get_target_temperature().has_value())
    this->target_temperature = *call.get_target_temperature();
  if (call.get_fan_mode().has_value())
    this->fan_mode = *call.get_fan_mode();
  if (call.get_swing_mode().has_value()) {
    this->swing_mode = *call.get_swing_mode();
  }
  if (!this->has_vane_select_) {
    if (call.has_custom_preset()) {
      std::string preset = call.get_custom_preset().str();
      if (!preset.empty()) {
        this->set_custom_preset_(preset.c_str());
        if (preset == "Top") {
          this->current_swing_code_ = SWING_CODE_TOP;
        } else if (preset == "Medium-Top") {
          this->current_swing_code_ = SWING_CODE_MEDIUM_TOP;
        } else if (preset == "Medium") {
          this->current_swing_code_ = SWING_CODE_MEDIUM;
        } else if (preset == "Medium-Bottom") {
          this->current_swing_code_ = SWING_CODE_MEDIUM_BOTTOM;
        } else if (preset == "Bottom") {
          this->current_swing_code_ = SWING_CODE_BOTTOM;
        } else {
          this->current_swing_code_ = SWING_CODE_AUTO;
        }
        // Choosing a vane position preset stops continuous vertical swing
        this->swing_mode = climate::CLIMATE_SWING_OFF;
      }
    }
  }

  this->transmit_state();
  this->publish_state();
}



uint8_t EG9Climate::reverse_bits(uint8_t data) const {
    uint8_t reversed = 0;
    for (int i = 0; i < 4; i++) { if ((data >> i) & 1) { reversed |= 1 << (3 - i); } }
    return reversed;
}

void EG9Climate::transmit_state() {
  uint8_t remote_state[14] = {0};
  
  if (this->mode == climate::CLIMATE_MODE_OFF) {
    const uint8_t off_frame[14] = {0xC4, 0xD3, 0x64, 0x80, 0x00, 0x04, 0xC0, 0xE0, 0x14, 0x00, 0x00, 0x00, 0x00, 0xE6};
    memcpy(remote_state, off_frame, 14);
  } else {
    // Build the 7-byte key from the current state
    std::vector<uint8_t> key(7);
    key[0] = EG9_POWER_ON;
    key[1] = (this->mode == climate::CLIMATE_MODE_HEAT) ? EG9_MODE_HEAT : EG9_MODE_COOL;

    uint8_t temp_val = EG9_TEMP_OFFSET - lroundf(this->target_temperature);
    key[2] = this->reverse_bits(temp_val) << 4;

    uint8_t fan_code;
    switch (this->fan_mode.value()) {
      case climate::CLIMATE_FAN_LOW:
        fan_code = FAN_CODE_LOW;
        break;
      case climate::CLIMATE_FAN_MEDIUM:
        fan_code = FAN_CODE_MEDIUM;
        break;
      case climate::CLIMATE_FAN_HIGH:
        fan_code = FAN_CODE_HIGH;
        break;
      case climate::CLIMATE_FAN_QUIET:
        fan_code = FAN_CODE_QUIET;
        break;
      default:
      case climate::CLIMATE_FAN_AUTO:
        fan_code = FAN_CODE_AUTO;
        break;
    }

    uint8_t swing_code;
    if (this->swing_mode == climate::CLIMATE_SWING_VERTICAL) {
      swing_code = SWING_CODE_CONTINUOUS;
    } else {
      swing_code = this->current_swing_code_;
    }
    key[3] = (fan_code << 5) | swing_code;
    
    key[4] = 0x00;
    key[5] = 0x00;
    key[6] = 0x00;

    // Find the key in the dictionary
    auto it = IR_CODE_DICTIONARY.find(key);
    if (it == IR_CODE_DICTIONARY.end()) {
        ESP_LOGW(TAG, "Could not find a command for the current state. Trying fallback...");
        
        // Determine a fallback swing code
        uint8_t fallback_swing_code = (swing_code == SWING_CODE_AUTO) ? SWING_CODE_TOP : SWING_CODE_AUTO;
        
        // Recalculate B9 with the fallback
        key[3] = (fan_code << 5) | fallback_swing_code;
        
        it = IR_CODE_DICTIONARY.find(key);
        if (it == IR_CODE_DICTIONARY.end()) {
            ESP_LOGE(TAG, "Fallback failed. Cannot transmit.");
            return;
        }
        ESP_LOGW(TAG, "Using fallback swing mode to transmit.");
    }

    // Build the final 14-byte command
    memcpy(remote_state, EG9_HEADER, 5);
    memcpy(remote_state + 5, key.data(), key.size());
    remote_state[12] = it->second.first;
    remote_state[13] = it->second.second;
  }

  // Transmit the command
  ESP_LOGD(TAG, "Sending IR frame: %02X %02X %02X %02X %02X %02X %02X %02X %02X %02X %02X %02X %02X %02X",
           remote_state[0], remote_state[1], remote_state[2], remote_state[3], remote_state[4], remote_state[5],
           remote_state[6], remote_state[7], remote_state[8], remote_state[9], remote_state[10], remote_state[11],
           remote_state[12], remote_state[13]);

  auto transmit = this->transmitter_->transmit();
  auto *data = transmit.get_data();
  data->set_carrier_frequency(38000);
  data->mark(3500); data->space(1650);
  for (int i = 0; i < 14; i++) {
    for (int j = 7; j >= 0; j--) {
      data->mark(450);
      data->space(((remote_state[i] >> j) & 1) ? 1200 : 400);
    }
  }
  data->mark(450); data->space(0);
  transmit.perform();
}

